import { createHash, randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

/** Must match EDITABLE_LEADERBOARD_SLUGS in credentials.ts */
const SLUGS = [
  "genai-agentic",
  "autonomous-control-system",
  "quant",
  "consult",
  "analytics",
  "product",
  "computer-vision",
  "ml-in-proteins",
  "ml-astronomy",
  "competitive-programming",
  "gamedev",
  "defi-builder-cohort",
];

function hashPassword(slug, password) {
  return createHash("sha256")
    .update(`csot-lb-editor:${slug}:${password}`)
    .digest("hex");
}

function randomPassword(length = 16) {
  const chars =
    "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
  const bytes = randomBytes(length);
  let out = "";
  for (let i = 0; i < length; i++) {
    out += chars[bytes[i] % chars.length];
  }
  return out;
}

const records = SLUGS.map((slug) => {
  const username = `csot-${slug}`;
  const password = randomPassword();
  const passwordHash = hashPassword(slug, password);
  return { slug, username, password, passwordHash };
});

const credentialsTs = `// AUTO-GENERATED by scripts/generate-leaderboard-credentials.mjs
// Do not edit by hand. Regenerate with: node scripts/generate-leaderboard-credentials.mjs

import { createHash, timingSafeEqual } from "node:crypto";

/** Open tracks with a DB-backed leaderboard editor (excludes devops, low-latency, cybersec). */
export const EDITABLE_LEADERBOARD_SLUGS = [
${SLUGS.map((s) => `  "${s}",`).join("\n")}
] as const;

export type EditableLeaderboardSlug = (typeof EDITABLE_LEADERBOARD_SLUGS)[number];

const EXCLUDED_EDITOR_SLUGS = new Set([
  "devops",
  "low-latency",
  "cybersec",
]);

type CredentialRecord = { username: string; passwordHash: string };

const CREDENTIALS: Record<EditableLeaderboardSlug, CredentialRecord> = {
${records
  .map(
    (r) =>
      `  "${r.slug}": { username: "${r.username}", passwordHash: "${r.passwordHash}" },`,
  )
  .join("\n")}
};

function hashPassword(slug: string, password: string): string {
  return createHash("sha256")
    .update(\`csot-lb-editor:\${slug}:\${password}\`)
    .digest("hex");
}

export function isEditableLeaderboardSlug(
  slug: string,
): slug is EditableLeaderboardSlug {
  return (
    (EDITABLE_LEADERBOARD_SLUGS as readonly string[]).includes(slug) &&
    !EXCLUDED_EDITOR_SLUGS.has(slug)
  );
}

export function verifyEditorCredentials(
  slug: EditableLeaderboardSlug,
  username: string,
  password: string,
): boolean {
  const record = CREDENTIALS[slug];
  if (!record) return false;
  if (record.username !== username.trim()) return false;
  const got = hashPassword(slug, password);
  const expected = record.passwordHash;
  if (got.length !== expected.length) return false;
  return timingSafeEqual(Buffer.from(got), Buffer.from(expected));
}

export function getEditorUsername(slug: EditableLeaderboardSlug): string {
  return CREDENTIALS[slug].username;
}
`;

const txt = `# CSoT'26 leaderboard editor credentials
# Generated: ${new Date().toISOString()}
# Share each block with the matching track lead. Edit URL: https://csot.devclub.in/tracks/<slug>/leaderboard/edit
# Regenerate: node scripts/generate-leaderboard-credentials.mjs
# DO NOT COMMIT — listed in .gitignore

${records
  .map(
    (r) =>
      `${r.slug}\n  URL: /tracks/${r.slug}/leaderboard/edit\n  Username: ${r.username}\n  Password: ${r.password}\n`,
  )
  .join("\n")}
`;

writeFileSync(join(root, "src/lib/leaderboard-editor/credentials.ts"), credentialsTs);
writeFileSync(join(root, "leaderboard-editor-credentials.txt"), txt);

